// Forged copy: balance edited after signing (signature no longer matches).
const signedBank = sign("bank-demo", bank.replace(/\n$/, ""), "2024-10-31T18:00:00Z");
writeFileSync("public/samples/forged_bank_statement.txt", bank.replace(/\n$/, "").replace("$84,250.00", "$984,250.00").replace("Closing Balance: $984,250.00", "Closing Balance: $984,250.00") + signedBank);

