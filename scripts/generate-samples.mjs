mkdirSync("public/samples", { recursive: true });
const write = (name, body, auth, date) => writeFileSync(`public/samples/${name}`, body.replace(/\n$/, "") + sign(auth, body.replace(/\n$/, ""), date));
write("bank_statement.txt", bank, "bank-demo", "2024-10-31T18:00:00Z");
write("aadhaar_offline_kyc.xml", aadhaar, "uidai-demo", "2024-10-31T12:00:00Z");
write("pan_card.txt", pan, "itd-demo", "2024-06-01T09:30:00Z");
