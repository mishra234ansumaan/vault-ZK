#!/usr/bin/env node
// Generates demo trust anchors (RSA-2048) and RSA-SHA256 signed sample documents.
// Private keys are discarded after signing. Replace src/lib/trust-anchors.ts with
// real authority public keys (UIDAI, ITD, ...) for production use.
import { generateKeyPairSync, createSign, createHash } from "node:crypto";
import { writeFileSync, mkdirSync } from "node:fs";

const authorities = [
  { id: "uidai-demo", name: "UIDAI (Demo Trust Anchor)", kind: "aadhaar" },
  { id: "itd-demo", name: "Income Tax Department (Demo Trust Anchor)", kind: "pan" },
  { id: "bank-demo", name: "Demo Bank Certificate Authority", kind: "bank" },
  { id: "revenue-demo", name: "Revenue Authority (Demo Trust Anchor)", kind: "tax" },
];

const keys = {};
for (const a of authorities) {
  const { publicKey, privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
  keys[a.id] = {
    ...a,
    spki: publicKey.export({ type: "spki", format: "der" }).toString("base64"),
    privateKey,
  };
}

function sign(authId, body, signedAt) {
  const k = keys[authId];
  const s = createSign("RSA-SHA256");
  s.update(body);
  const sig = s.sign(k.privateKey).toString("base64");
  const kid = createHash("sha256").update(k.spki).digest("hex").slice(0, 16);
  return [
    "",
    "-----BEGIN VZK SIGNATURE-----",
    `Authority: ${k.name}`,
    `Key-Id: ${authId}`,
    `Key-Fingerprint: ${kid}`,
    "Algorithm: RSA-SHA256-PKCS1v1.5",
    `Signed-At: ${signedAt}`,
    `Signature: ${sig}`,
    "-----END VZK SIGNATURE-----",
    "",
  ].join("\n");
}

